"""Build static locale entry points from the English homepage and localized copy."""

import json
import re
import sys
from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEXT = re.compile(r"<!--locale:([\w-]+)-->(.*?)<!--/locale-->", re.DOTALL)
ATTRIBUTE = re.compile(r'([\w-]+)="([^"]*)" data-locale-\1="([\w-]+)"')
BADGE_LOCALE = {
    "zh-CN": "zh-Hans",
    "zh-TW": "zh-Hant",
    "zh-HK": "zh-Hant",
    "ja": "ja",
    "ko": "ko",
}


def render_home(source, language, copy):
    html = TEXT.sub(lambda match: copy.get(match[1], match[2]), source)
    html = ATTRIBUTE.sub(
        lambda match: f'{match[1]}="{escape(copy[match[3]], quote=True) if copy else match[2]}"',
        html,
    )
    html = html.replace(' lang="en"', f' lang="{language}"')
    html = html.replace(
        'rel="canonical" href="https://focus.flights/"',
        f'rel="canonical" href="https://focus.flights/{language}/"',
    )
    html = html.replace('  <script src="/locales/preference.js"></script>\n', "")
    if copy:
        badge = BADGE_LOCALE[language]
        html = html.replace(
            "/brand/download-on-the-app-store.svg", f"/brand/localized/{badge}-app.svg"
        ).replace(
            "/brand/download-on-the-mac-app-store.svg", f"/brand/localized/{badge}-mac-app.svg"
        )
        html = html.replace(
            "/gift/studio-portrait.webp?v=hidden-black-week", f"/gift/localized/{language}-portrait.webp"
        ).replace(
            "/gift/studio.webp?v=hidden-black-week", f"/gift/localized/{language}-wide.webp"
        )
        art = f"/gift/localized/{language}.webp"
        html = html.replace(
            f'<html lang="{language}">',
            f'<html lang="{language}" data-gift-atlas="{art}" style="--gift-atlas: url({art})">',
        )
    return html.replace(
        "<!doctype html>", "<!doctype html>\n<!-- Generated by tools/build-locales.py from index.html. -->", 1
    )


def main():
    source = (ROOT / "index.html").read_text(encoding="utf-8")
    localizations = json.loads((ROOT / "locales/home.json").read_text(encoding="utf-8"))
    keys = {match[1] for match in TEXT.finditer(source)} | {match[3] for match in ATTRIBUTE.finditer(source)}
    check = sys.argv[1:] == ["--check"]
    for language, copy in {"en": {}, **localizations}.items():
        if copy and (missing := keys - copy.keys()):
            raise SystemExit(f"{language}: missing translations for {', '.join(sorted(missing))}")
        output = ROOT / language / "index.html"
        html = render_home(source, language, copy)
        if check:
            if not output.exists() or output.read_text(encoding="utf-8") != html:
                raise SystemExit(f"{output.relative_to(ROOT)} is outdated. Run python3 tools/build-locales.py.")
        else:
            output.parent.mkdir(exist_ok=True)
            output.write_text(html, encoding="utf-8")


if __name__ == "__main__":
    main()
